/**
 * Score a list of public repos and write docs/leaderboard.md + docs/leaderboard.json.
 * Usage: GITHUB_TOKEN=... node dist/scripts/leaderboard.js [scripts/leaderboard-repos.txt]
 * The token (optional, raises the API limit) is sent only to api.github.com.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { score } from "../src/score.js";
import { GitHubSource, parseGitHubTarget } from "../src/sources/github.js";
import type { Report } from "../src/types.js";

const listFile = process.argv[2] ?? "scripts/leaderboard-repos.txt";
const repos = readFileSync(listFile, "utf8").split("\n").map((s) => s.trim()).filter(Boolean);

const reports: Report[] = [];
const failed: string[] = [];
for (const r of repos) {
  const t = parseGitHubTarget(r);
  if (!t) continue;
  try {
    reports.push(await score(new GitHubSource(t, { token: process.env.GITHUB_TOKEN })));
    process.stderr.write(".");
  } catch (e) {
    failed.push(`${r}: ${(e as Error).message}`);
  }
}
process.stderr.write("\n");

reports.sort((a, b) => b.score - a.score || a.repo.localeCompare(b.repo));
const code = reports.filter((r) => r.kind === "code");
const content = reports.filter((r) => r.kind === "content");
const scores = code.map((r) => r.score).sort((a, b) => a - b);
const median = scores.length ? scores[Math.floor((scores.length - 1) / 2)]! : 0;
const share = (id: string) => Math.round((100 * code.filter((r) => r.results.find((c) => c.id === id)?.status === "pass").length) / Math.max(1, code.length));
const gapOf = (r: Report) => {
  const gap = [...r.results].filter((c) => c.status !== "pass").sort((a, b) => b.maxPoints - b.points - (a.maxPoints - a.points))[0];
  return gap ? `${gap.title} (-${gap.maxPoints - gap.points})` : "none";
};
const date = new Date().toISOString().slice(0, 10);

const md = [
  `# Agent-readiness of the most-starred AI repos (${date})`,
  "",
  `${code.length} AI/agent code repositories seen on GitHub Trending between 2026-07-28 and 2026-10-25, ranked by readyrepo score. ${content.length} content repos (skill packs, lists, tutorials) are listed separately and not ranked, because the code checks don't apply to them.`,
  `Median score (code repos): **${median}/100**. Generated by \`scripts/leaderboard.ts\`; methodology in [checks.md](checks.md).`,
  "",
  "| Share of code repos that pass | |",
  "|---|---|",
  `| Agent instructions file at the root | ${share("instructions-file")}% |`,
  `| Instructions include runnable commands | ${share("instructions-commands")}% |`,
  `| One discoverable test command | ${share("test-command")}% |`,
  `| CI | ${share("ci")}% |`,
  `| Lockfile | ${share("lockfile")}% |`,
  "",
  "| # | Repo | Score | Biggest gap |",
  "|---|---|---|---|",
  ...code.map((r, i) => `| ${i + 1} | [${r.repo}](https://github.com/${r.repo}) | ${r.score} | ${gapOf(r)} |`),
  ...(content.length ? ["", "## Content repos (not ranked)", "", "| Repo | Score | Biggest gap |", "|---|---|---|",
    ...content.map((r) => `| [${r.repo}](https://github.com/${r.repo}) | ${r.score} | ${gapOf(r)} |`)] : []),
  ...(failed.length ? ["", `Not scored (${failed.length}): ${failed.join("; ")}`] : []),
  "",
].join("\n");

writeFileSync("docs/leaderboard.md", md);
writeFileSync("docs/leaderboard.json", JSON.stringify({ date, median, reports }, null, 1));
console.log(`scored ${reports.length}, failed ${failed.length}, median ${median}`);
